package com.maruseron.zeron;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;

/**
 * Generates the command and manifest reference chapters from {@link CliMetadata}.
 *
 * <p>Run from the repository root with:
 * {@code java -cp target/classes com.maruseron.zeron.DocumentationGenerator}</p>
 */
public final class DocumentationGenerator {
    private static final String NOTICE = """
            <!-- Generated from src/main/java/com/maruseron/zeron/CliMetadata.java.
                 Do not edit this file manually; regenerate it with the documented command. -->
            """;

    private DocumentationGenerator() {}

    public static void main(final String... args) throws IOException {
        final var guide = Path.of(args.length > 0 ? args[0] : "guide");
        Files.createDirectories(guide);
        Files.writeString(guide.resolve("39-command-reference.md"), renderCommandReference());
        Files.writeString(guide.resolve("40-manifest-reference.md"), renderManifestReference());
        System.out.println("Regenerated guide/39-command-reference.md and guide/40-manifest-reference.md.");
    }

    static String renderCommandReference() {
        final var builder = new StringBuilder(NOTICE);
        builder.append("""

                # Command reference

                This chapter is the complete command and option reference for the `zeron` launcher.
                The command line is parsed by `CliParser`, help is rendered by `CliHelp`, and this page is
                generated from `CliMetadata`; run
                `java -cp target/classes com.maruseron.zeron.DocumentationGenerator` from the repository
                root after changing the metadata.

                ## Exit behavior

                Successful commands exit with status 0. Invalid invocations, including unknown targets and
                conflicting options, exit with status 64. A parse or resolution failure exits with status 65
                or 71, and a compilation failure exits with status 70. With `--deny-warnings`, reported
                warnings fail a successful stage with status 71.

                ## Commands

                """);
        for (final var command : CliMetadata.COMMANDS) {
            builder.append("### `").append(command.name()).append("`\n\n")
                    .append("```text\n").append(command.synopsis()).append("\n```\n\n")
                    .append(command.summary()).append("\n");
            if (!command.details().isEmpty()) builder.append('\n').append(command.details()).append('\n');
            builder.append('\n');
        }
        builder.append("""
                ## Options

                Options are accepted only by the commands listed for them. Unknown dash-prefixed arguments
                are reported as options. `--deny-warnings` and `--no-deny-warnings` cannot be combined.

                """);
        for (final var option : CliMetadata.OPTIONS) {
            builder.append("### `").append(option.name()).append("`\n\n")
                    .append("```text\n").append(option.synopsis()).append("\n```\n\n")
                    .append(option.summary()).append("\n\n")
                    .append(option.details()).append("\n\n");
            if (!option.commands().isEmpty()) {
                builder.append("Applies to: `").append(String.join("`, `",
                        option.commands().stream().sorted().toList())).append("`.\n\n");
            }
        }
        builder.append("""
                ## Target selection and precedence

                `zeron build` and `zeron run` accept one optional positional target name. With no name, the
                command selects `[project].default-target`; when no default target is configured, it selects
                the implicit project target described by `[project].entry` and `[project].output`.

                Effective settings resolve from built-in defaults, then `[project]` and `[build]`, then the
                selected `[targets.<name>]` entry, then explicit command-line options. An unknown target is
                an invalid invocation and reports the available target names.
                """);
        return builder.toString();
    }

    static String renderManifestReference() {
        final var builder = new StringBuilder(NOTICE);
        builder.append("""

                # Project manifest reference

                `zeron.toml` is a declarative description of compilation inputs and project targets. It is
                TOML, and every path inside it resolves relative to the manifest file unless the path is
                absolute. The accepted top-level tables are `[project]`, `[platform]`, `[dependencies]`,
                `[build]`, and `[targets.<name>]`; unknown keys in any table are rejected.

                """);
        for (final var table : CliMetadata.MANIFEST_TABLES) {
            builder.append("## `[").append(table.name()).append("]`\n\n")
                    .append(table.summary()).append("\n\n")
                    .append("| Key | Type | Default | Requirement | Description | Constraints |\n")
                    .append("| --- | --- | --- | --- | --- | --- |\n");
            for (final var key : table.keys()) {
                builder.append("| `").append(key.name()).append("` | ")
                        .append(key.type()).append(" | ")
                        .append(key.defaultValue()).append(" | ")
                        .append(key.required()).append(" | ")
                        .append(key.description()).append(" | ")
                        .append(key.constraints()).append(" |\n");
            }
            builder.append('\n');
        }
        builder.append("""
                ## Path resolution

                Relative paths resolve against the directory containing the manifest. Source roots must
                exist and be directories. Every target entry must exist, have a `.zn` extension, and reside
                under one of the configured source roots. Output directories may be new, but their nearest
                existing parent must be writable.

                ## Targets and outputs

                A named target inherits `[project].entry` unless it declares its own `entry`, and defaults
                its output to `<project.output>/<name>`. The implicit project target uses
                `[project].output` exactly. Normalized effective output directories must be distinct, so
                building one target cannot overwrite another; a target that intentionally shares the
                project output directory with the implicit target must set that path explicitly.

                Target names are case-sensitive and must match `[A-Za-z][A-Za-z0-9_-]*`.
                `[project].default-target` must name an existing target. Target entries participate in the
                project-wide source set, so the language server and formatter see them regardless of the
                target last built.

                ## Warning policy and precedence

                `[build].deny-warnings` applies to every target. A target may override it, and
                `--deny-warnings` or `--no-deny-warnings` overrides both. `--no-warnings` only hides warning
                output; it does not change the deny policy. Effective settings resolve in this order:

                1. built-in defaults;
                2. `[project]` facts and `[build]` policy;
                3. the selected `[targets.<name>]` overrides;
                4. explicit command-line options.

                The same resolved entry, output, and policy are used by `zeron build` and `zeron run`, so a
                target cannot build differently from how it runs.
                """);
        return builder.toString();
    }
}
